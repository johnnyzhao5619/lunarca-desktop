//! 云插件 ACL 覆盖守护（ADR-037 纵切 1.5 真机验收发现）。
//!
//! **这几条断言全部来自真机故障，不是预防性洁癖**。被 ACL 拒绝的 invoke 返回的对象
//! **不带 `code` 字段**，前端的 `error.${code}` 就渲染成 `error.undefined`——单测全绿、
//! 类型检查全过，只有真机看得见。
//!
//! 踩到的三层坑，各配一条断言：
//! 1. 插件根本没有权限清单（补 `build.rs` + `permissions/default.toml`）；
//! 2. 补了清单仍不生效——**ACL 命名空间取自 crate 名，权限匹配却用运行时插件名**，
//!    两者不一致（`luna-cloud` vs `lunarca-cloud`）时权限对不上号，照样全拒；
//! 3. **清单与真实命令面脱节**（2026-08-08 第二次真机撞上，同一个 `error.undefined`）：
//!    新增一条云命令时只改了 `commands.rs` 的联网姿态表（那条测试会变红），
//!    而 `build.rs` 的 `COMMANDS` 无人提醒——于是命令注册了、绑定生成了、tsc 过了、
//!    `cargo test` 全绿，真机上却被 ACL 静默拒绝。
//!
//!    **前两条守护为什么没拦住**：它们比对的是「测试里硬编码的清单」与「生成的权限文件」，
//!    两份都由人手维护、且都没变，自然一致。**没有任何一条把清单与真实命令面对上**——
//!    守护守的是清单内部自洽，不是清单是否完整。故本轮把那份硬编码清单**删掉**，
//!    改为从 `build.rs` 解析（唯一事实源），并新增第 4 条断言把它与 `#[tauri::command]`
//!    的实际集合钉死：以后加命令，这里会主动变红并直接告诉你该改哪个文件。

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

fn cloud_crate() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../crates/luna-cloud")
}

/// `build.rs` 的 `COMMANDS`——**ACL 侧的唯一事实源**（权限文件由它生成）。
fn acl_commands() -> BTreeSet<String> {
    let src = std::fs::read_to_string(cloud_crate().join("build.rs")).expect("读不到 build.rs");
    let body = src
        .split("const COMMANDS: &[&str] = &[")
        .nth(1)
        .and_then(|rest| rest.split("];").next())
        .expect("build.rs 里找不到 COMMANDS 清单");
    body.lines()
        .filter_map(|line| {
            let token = line.trim().trim_end_matches(',');
            if token.starts_with('"') && token.ends_with('"') && token.len() > 2 {
                Some(token.trim_matches('"').to_owned())
            } else {
                None
            }
        })
        .collect()
}

/// `commands.rs` 里实际带 `#[tauri::command]` 的函数名——**运行时真正暴露的那一组**。
/// 读源码而非引运行时（与 `luna_cloud::commands` 的联网姿态表同一手法，零额外依赖）。
fn declared_commands() -> BTreeSet<String> {
    let src =
        std::fs::read_to_string(cloud_crate().join("src/commands.rs")).expect("读不到 commands.rs");
    let mut names = BTreeSet::new();
    let mut armed = false;
    for line in src.lines() {
        let line = line.trim();
        if line == "#[tauri::command]" {
            armed = true;
            continue;
        }
        if !armed {
            continue;
        }
        if let Some(rest) = line
            .strip_prefix("pub async fn ")
            .or_else(|| line.strip_prefix("pub fn "))
        {
            if let Some(name) = rest.split(['(', '<']).next() {
                names.insert(name.trim().to_owned());
                armed = false;
            }
        }
    }
    names
}

/// **第 4 条：ACL 清单必须等于真实命令面。**
///
/// 前三条守的是"清单内部自洽"，这一条守的是"清单是否完整"——两者是不同的问题，
/// 而真机上表现完全一样（整块功能 `error.undefined`）。少一条 = 那个命令被静默拒绝；
/// 多一条 = 生成一份没有对应命令的权限（无害但会掩盖删除时的遗漏）。
#[test]
fn acl_command_list_matches_the_real_command_surface() {
    assert_eq!(
        acl_commands(),
        declared_commands(),
        "`crates/luna-cloud/build.rs` 的 COMMANDS 与 `commands.rs` 的 `#[tauri::command]` 不一致。\n\
         少列的命令会被 Tauri ACL **静默拒绝**：invoke 返回的对象不带 `code`，\n\
         前端渲染成 `error.undefined`，而单测、tsc、clippy 全都是绿的——只有真机看得见。\n\
         加/删云命令时，`build.rs` 与 `commands.rs` 的姿态表**两处都要改**。"
    );
}

#[test]
fn every_cloud_command_has_an_autogenerated_permission() {
    let dir = cloud_crate().join("permissions/autogenerated/commands");
    for command in &acl_commands() {
        let file = dir.join(format!("{command}.toml"));
        assert!(
            file.exists(),
            "云命令 `{command}` 缺自动生成的权限文件（{}）。\n\
             它没被 build.rs 的 COMMANDS 列出 → ACL 会拒掉它 → 真机上该功能整块失效。",
            file.display()
        );
    }
}

#[test]
fn default_permission_set_covers_every_command() {
    let toml = std::fs::read_to_string(cloud_crate().join("permissions/default.toml"))
        .expect("云插件缺 permissions/default.toml");
    let listed: BTreeSet<String> = toml
        .lines()
        .filter_map(|line| {
            let token = line.trim().trim_end_matches(',').trim_matches('"');
            token
                .strip_prefix("allow-")
                .map(|rest| rest.replace('-', "_"))
        })
        .collect();
    let expected: BTreeSet<String> = acl_commands();
    assert_eq!(
        listed, expected,
        "default 权限集与命令面不一致。未列出的命令会被 ACL 静默拒绝——\n\
         单测依然全绿，用户在真机上看到的却是一整面报错。"
    );
}

/// 最隐蔽的一条：ACL 命名空间（crate 名/links）必须等于运行时插件名。
#[test]
fn acl_namespace_matches_runtime_plugin_name() {
    let manifest =
        std::fs::read_to_string(cloud_crate().join("Cargo.toml")).expect("读不到 Cargo.toml");
    let links = manifest
        .lines()
        .find_map(|l| l.trim().strip_prefix("links = "))
        .map(|v| v.trim().trim_matches('"').to_owned())
        .expect("云插件缺 links 字段——tauri-plugin 的 ACL 生成据此定位权限清单");

    let lib = std::fs::read_to_string(cloud_crate().join("src/lib.rs")).expect("读不到 lib.rs");
    let plugin_name = lib
        .lines()
        .find_map(|l| l.trim().strip_prefix("pub const PLUGIN_NAME: &str = "))
        .map(|v| v.trim().trim_end_matches(';').trim_matches('"').to_owned())
        .expect("找不到 PLUGIN_NAME");

    assert_eq!(
        links, plugin_name,
        "ACL 命名空间（links = {links}）与运行时插件名（PLUGIN_NAME = {plugin_name}）不一致。\n\
         Tauri 按运行时插件名匹配权限，按 links 生成权限——不一致时权限写得再全也对不上号，\n\
         所有云命令被静默拒绝，真机表现为账户面板整面 `error.undefined`。"
    );

    let caps = std::fs::read_to_string(
        Path::new(env!("CARGO_MANIFEST_DIR")).join("capabilities/default.json"),
    )
    .expect("读不到 capabilities/default.json");
    assert!(
        caps.contains(&format!("{plugin_name}:default")),
        "应用能力集没有引用 `{plugin_name}:default`——插件权限写得再全也不会生效。"
    );
}
